def check_online_lookup(browser, base: str, output: Path, symbol: str) -> None:
    page = browser.new_page(viewport={"width": 1440, "height": 900})
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    page.goto(base + "compare.html", wait_until="domcontentloaded")
    lookup = page.locator("#company-lookup")
    lookup.get_by_text("Look up on NSE", exact=True).click()
    query = lookup.locator('input[name="q"]')
    search = lookup.get_by_role("button", name="Search NSE")
    add = lookup.get_by_role("button", name=f"Add {symbol}", exact=True)
    matches = "**/api/company-lookup?*"
    query.fill(symbol)
    with page.expect_response(matches, timeout=30_000) as response:
        search.click()
    directory = response.value.json()
    identity = next(candidate for candidate in directory["matches"] if candidate["symbol"] == symbol)
    assert directory["mode"] in {"fetched", "retained"} and identity["isin"], directory
    with page.expect_response("**/api/company-lookup", timeout=60_000) as response:
        add.click()
    imported = response.value.json()
    assert response.value.ok and imported["state"] in {"added", "already_added"}, imported
    row = imported["row"]
    assert row["coverage"] == "annual" and row["price_inr"] and row["quote_as_of"], imported
    assert row["identity"]["isin"] == identity["isin"], imported
    expect(lookup.locator(".lookup-status")).to_contain_text("Annual statements available")
    preview = output / f"lookup-{symbol.lower()}-desktop.png"
    if imported["state"] == "added" or not preview.is_file():
        page.screenshot(path=str(preview))

    column = page.locator("#compare-columns").locator(f'[data-company="{row["id"]}"]')
    column.get_by_role("button", name="Company detail").click()
    detail = page.frame_locator("#company-frame")
    expect(detail.locator("#co-name")).to_contain_text(row["name"])
    expect(detail.locator('[data-chart="operating-revenue"] path.history-line')).to_have_count(1)
    detail.get_by_role("button", name=re.compile(r"^Revenue from operations:")).click()
    expect(detail.locator('#drawer-body a[href*="screener.in/company/"]')).to_have_count(1)
    detail.locator("#drawer-close").click()
    detail.locator("#quote-src").click()
    expect(detail.locator('#drawer-body a[href*="nsearchives.nseindia.com"]')).to_have_count(1)
    page.locator("#company-details-close").click()

    query.fill(identity["isin"])
    with page.expect_response(matches) as response:
        search.click()
    alias = response.value.json()
    assert alias["count"] == 1 and alias["matches"][0]["symbol"] == symbol, alias
    with page.expect_response("**/api/company-lookup") as response:
        add.click()
    assert response.value.json()["state"] == "already_added"
    expect(column).to_have_count(1)
    page.reload(wait_until="domcontentloaded")
    expect(column).to_be_visible()

    page.goto(base + "?company=igx", wait_until="domcontentloaded")
    lookup.get_by_text("Look up on NSE", exact=True).click()
    query.fill(symbol)
    search.click()
    add.click()
    expect(page.locator("#co-name")).to_contain_text(row["name"])
    page.get_by_role("link", name="Compare this company").click()
    expect(column).to_be_visible()
    assert not errors, errors
    page.close()
    (output / f"lookup-{symbol.lower()}-checks.json").write_text(json.dumps({
        "directory": directory["mode"], "initial_add": imported["state"], "sources": imported["sources"],
        "company": row["id"], "isin": identity["isin"], "quote_as_of": row["quote_as_of"],
        "detail_sources_visible": True, "isin_reused_record": True, "column_restored_after_reload": True,
        "dashboard_lookup_handoff": True,
    }, indent=2), encoding="utf-8")
    print(f"desktop: {symbol} directory, annual and price evidence, ISIN deduplication and reload")


